import Foundation

/// Маршруты приложения — 1:1 таблице «Имена корневых вью» из
/// `spec/INTEGRATION.md`. Каждый case и его параметры совпадают буквально с
/// тем, что описано в контракте (`taskID`, `noteID`, `projectID`, `labelID`) —
/// это то, что писатели экранов ждут от навигации по правилу контракта
/// «переход на другой экран — через маршрут из таблицы».
///
/// `/inbox` сознательно отсутствует — маршрут убран из веба 26.08.2026,
/// нативного аналога нет (см. INTEGRATION.md).
public enum AppRoute: Hashable {
    /// Совместимый маршрут: после объединения 06.09 «Сегодня» открывает
    /// первый раздел единого «Планирования».
    case today
    case overview
    case upcoming
    case timeline
    case chat
    case taskDetail(taskID: String)
    /// Единственный отдельный сценарий формы — создание новой задачи.
    /// Существующие задачи всегда открываются через `taskDetail`.
    case taskCreate
    case notes
    /// Прямое создание из центрального «+»: сначала открывается база, затем
    /// создаётся документ и сразу показывается его редактор.
    case noteCreate
    /// Дневник, сразу открытый на конкретной папке (просьба владельца
    /// 03.09.2026: шеврон «Документация» у проекта вёл на общий несвязанный
    /// корень Заметок — не та папка, что показана в превью карточки проекта).
    /// `.notes` без параметра НЕ трогаем — контракт `INTEGRATION.md` его
    /// таким и описывает, этот case — целенаправленное добавление сверх него.
    case noteFolder(folderID: Int)
    case noteEditor(noteID: String)
    case projects
    /// Прямое создание из центрального «+»: открывает «Проекты» сразу с
    /// существующей формой создания, а не просто список проектов.
    case projectCreate
    /// Смысловой поиск по документации всех проектов (KnowledgeScreen).
    case knowledge
    case projectTasks(projectID: String)
    /// Задачи без проекта — тот же экран списка, но `projectID == nil`.
    case noProjectTasks
    case labels
    case labelTasks(labelID: String)
    case search
    case activity
    case notifications
    case agents
    /// Очередь запусков ролей (LOCK-208) — только для владельца.
    case roleRunJobs
    /// Память ролей (02.10.2026) — что команда знает; владелец видит и правит.
    case memory
    /// `focus` — с какого состояния открыть сводку. Четыре плитки «Обзора»
    /// («В работе», «На проверке», «Заблокированы», «Пропали») вели сюда без
    /// параметра, и каждая показывала один и тот же полный список: владелец
    /// 09.09.2026 — «зачем нам эти четыре кнопки, если все ведут в одно
    /// место». `nil` — открыть всё, как раньше.
    case agentWork(focus: AgentWorkFocus? = nil)
    case settings
    case integrations
    case templates
    case voiceModels
    /// LOCK-218: Настройки → ИИ → выбор голоса Секретаря с прослушиванием.
    case secretaryVoicePicker
    /// LOCK-179: серверный AI — провайдеры и модели Pi (`/api/runtime/*`).
    /// Локальные модели остаются на `.voiceModels` («На устройстве»).
    case runtimeProviders
    case providerDetail(providerID: String)
    /// LOCK-180: статус Pi Runtime из «Настройки → Сервер».
    case runtimeStatus
    /// LOCK-181: сервисные учётки (`ApiUser` + API-токен), переехали из «Команды».
    case serviceAccounts
    /// LOCK-183: профиль роли из плоского списка «Команды» (`id` — role).
    case agentProfile(id: String)
    /// LOCK-195: чат с ролями открывается маршрутом, а не передачей значения.
    /// Маршрут — единственная форма пуша, которая кладёт элемент в
    /// `NavigationPath`; по нему `RootShellView` понимает, что на вкладке есть
    /// пуш, и прячет панель вкладок. С формой `NavigationLink { }` панель
    /// оставалась и накрывала панель ввода чата (найдено 21.09.2026).
    case roleChat(id: String)
    /// LOCK-195: прежний owner-канал «Секретарь» (надиктовать → карточка) —
    /// тот же экран `ChatScreen`, но открытый из списка чатов.
    case secretaryChat
    /// Голосовой разговор с Секретарём через LiveKit (Задача 5 плана Супер
    /// Секретарь) — отдельный полноэкранный маршрут поверх комнаты
    /// `chat-secretary`.
    case secretaryVoiceCall
}
