#!/usr/bin/env bash
#
# Запуск агента Antigravity — его собственный CLI (`agy`), а не самописная
# обвязка и не Gemini CLI.
#
# История вопроса. Сначала здесь был antigravity_agent.py: 496 строк своего
# цикла с семью захардкоженными инструментами и самодельным разбором вызовов.
# Он не доводил работу до конца — цифры с машины снимал верные, а шаг на доске
# не закрывал и на проверку не сдавал. Потом сюда встал Gemini CLI, но у него
# для физлица бесплатный тариф с лимитом в несколько запросов (и, по нашему же
# разбору от 06.08.2026, Google вообще увёл индивидуальные аккаунты из Gemini
# CLI в Antigravity). Сейчас — родной `agy`: вход под аккаунтом Максима, доска
# через MCP, модели Gemini 3.x и сверх того Claude Sonnet/Opus и GPT-OSS.
#
# Что делает обёртка, кроме запуска:
#   • уводит запросы в свой выход (см. xray-antigravity.service): общий прокси
#     смотрит в Финляндию, а оттуда Google отвечает «User location is not
#     supported»;
#   • держит рабочей папкой репозиторий TaskFlow, чтобы агент видел код.
#
# Ключ Gemini здесь больше не нужен: вход выполнен аккаунтом, учётка лежит у
# `agy` в его собственном хранилище.
#
# Аргументы прилетают от сторожа как есть: --model <модель> -p <текст задания>.
set -uo pipefail

export PATH="/home/maksim/.local/bin:$PATH"

PROXY="${ANTIGRAVITY_PROXY:-http://127.0.0.1:10814}"
export HTTPS_PROXY="$PROXY" HTTP_PROXY="$PROXY" https_proxy="$PROXY" http_proxy="$PROXY"

# Сторож запускается через vault-run и держит в окружении СВОЙ ключ доски
# (TASKFLOW_TOKEN = учётка Claude_Bot). Дочерний процесс наследует его, а
# mcp_server.py смотрит на эту переменную ПЕРЕД тем как лезть в хранилище —
# и агент ходит по доске под чужим именем. Прецедент 24.08.2026: Antigravity
# честно отработал карточку, а в ленте все его действия подписаны Claude_Bot,
# и Максим спросил «ты сам её выполнил, что ли?». Убираем переменную, чтобы
# MCP взял ключ по имени из конфига — TASKFLOW_ANTIGRAVITY_TOKEN.
unset TASKFLOW_TOKEN

cd /home/maksim/Проекты/New-Todoist

# Спрашивать подтверждение не у кого: сторож запускает процесс без терминала,
# и на любом вопросе агент просто повиснет до таймаута.
# Заход по умолчанию обрывался через 5 минут («Error: timeout waiting for
# response») — столько у agy стоит --print-timeout. Реальная задача по коду
# в эти пять минут не укладывается: 29.08.2026 три карточки подряд ушли в
# blocked именно по таймауту, а не по отказу модели. Двадцати минут хватает
# с запасом; служба всё равно держит свой предел в час.
exec /home/maksim/.local/bin/agy --dangerously-skip-permissions --print-timeout 20m "$@"
