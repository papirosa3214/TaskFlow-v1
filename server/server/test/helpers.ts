// Общая подготовка состояния для тестов протокола агента.
//
// Зачем файл. 10.09.2026 в наборе висело 13 падений в 7 файлах, и у всех была
// одна причина: тесты писались до того, как появился флаг готовности
// (`ready_for_pickup`). Агент не может взять задачу, пока владелец её не
// подтвердил, поэтому `claim` отдавал 400 — а дальше каскадом падало всё, что
// шло после него.
//
// Максим тогда предложил сделать для тестов исключение на сервере. Не стали:
// флаг — настоящая ступень протокола, и если выключать её под тестами, набор
// станет зелёным на пути, которого в жизни нет, а в ветке «под тестами иначе»
// рано или поздно спрячется реальный баг. Вместо этого — одна строка здесь.
//
// Почему прямым UPDATE, а не через API: это ПОДГОТОВКА состояния, такая же, как
// `UPDATE users SET type='ai'` в тех же тестах. Сам флаг как поведение (кто
// вправе его поднять, что пишется в ленту) проверяется через API в
// readyFlag.test.ts, а сквозной e2e.test.ts намеренно идёт полным путём
// владельца — там PATCH, а не этот помощник.
import db from "../src/db.js";

/** Владелец подтвердил задачу — агент вправе её взять. */
export function markReadyForPickup(taskId: string): void {
  db.prepare("UPDATE tasks SET ready_for_pickup = 1 WHERE id = ?").run(taskId);
}
