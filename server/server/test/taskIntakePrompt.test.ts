// Формат разбора надиктовки и двухслойный промпт постановки
// (разделы 6 и 7 спецификации от 14.09.2026).
//
// Системный слой принадлежит серверу: схема ответа, допустимые проекты,
// запрет запускать задачу. Слой владельца (scope `task_intake`) управляет
// смыслом — стилем названий, глубиной разбиения. До 14.09.2026 разбор шёл
// на одной зашитой константе, и сохранённый владельцем промпт к этому
// пути не был подключён вовсе.
import { describe, expect, it } from "vitest";

const { buildDictationSystemPrompt } = await import("../src/routes/ai.js");

describe("Двухслойный промпт постановки", () => {
  it("без текста владельца работает шаблон постановки", () => {
    const prompt = buildDictationSystemPrompt("");
    expect(prompt).toContain("ШАБЛОН");
    expect(prompt).toContain('"role"');
    expect(prompt).toContain('"where"');
  });

  it("пустой текст из пробелов не считается текстом владельца", () => {
    expect(buildDictationSystemPrompt("   \n  ")).toEqual(
      buildDictationSystemPrompt(""),
    );
  });

  // 23.09.2026: что владелец видит в «Постановке задач», то и работает —
  // его текст заменяет шаблон, а не приклеивается к нему.
  it("текст владельца заменяет шаблон целиком", () => {
    const own = "Названия пиши глаголом. Дроби на дерево охотнее.";
    expect(buildDictationSystemPrompt(own)).toBe(own);
  });

  it("системный слой требует критерий результата и вопрос владельцу", () => {
    // Раздел 7: у каждой исполняемой карточки должны быть проверяемый
    // признак готовности и, если работу нельзя сделать надёжно, —
    // конкретный вопрос. Без них постановка неполная: по первой нельзя
    // принять работу, по второму автомат не поймёт, что запускать нельзя.
    const prompt = buildDictationSystemPrompt("");
    expect(prompt).toContain('"result"');
    expect(prompt).toContain('"question"');
    // Вопрос — не вежливость: он останавливает запуск.
    expect(prompt).toContain("ОСТАНАВЛИВАЕТ");
  });
});
