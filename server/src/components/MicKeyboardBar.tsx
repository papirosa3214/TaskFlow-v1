import { createPortal } from "react-dom";
import { Icon } from "./UI";

// ═══════════ Микрофон над клавиатурой ═══════════
//
// Owner 2026-08-13 (пятый заход, итог): «влезть» физически поверх
// системной accessory-панели iOS (стрелочки/Done) невозможно — не баг
// вёрстки, архитектурное ограничение платформы. Та панель не DOM-узел
// страницы, а часть системного UI-слоя браузера (browser chrome),
// который композитится ОС/движком поверх содержимого страницы; веб-
// контенту (z-index, position:fixed — не важно что) туда доступа нет в
// принципе. Проверено не на глаз: тот же принцип независимо подтверждают
// Apple Developer Forums на соседнем случае — position:fixed контент
// физически обрезается, если пытается зайти под системные browser
// controls, а не отрисовывается поверх них.
// Четвёртый заход (компенсация -121px, прозрачный фон, «слиться» с
// системной панелью) исходил из неверной посылки — что раз нельзя
// добавить кнопку В панель, можно хотя бы нарисовать поверх нее; владелец
// проверил вживую — кнопка физически недоступна для тапа (закрыта
// системным слоем). Возврат к рабочему месту: `bottom: var(--kb-inset)`,
// ровно ВЫШЕ системной панели, там кнопка реально кликабельна — это
// подтверждённая рабочая зона, не гипотеза. Визуально — не полноширинная
// плашка (её раньше сочли слишком «в лоб»), а компактная плавающая
// кнопка-таблетка, полупрозрачный фон+блюр, чтобы не выглядеть чужеродной
// панелью, а лёгким плавающим элементом.
//
// Восьмой заход (owner 2026-08-13, живой баг на телефоне) — ГИПОТЕЗА НЕ
// ПОДТВЕРДИЛАСЬ: считал, что причина — кратковременный провал --kb-inset
// к 0 при blur/focus между полями, защищался
// max(var(--kb-inset), env(safe-area-inset-bottom)). Не сработало —
// safe-area-inset-bottom (~34px) не может исправить провал внутрь зоны
// клавиатуры (~300px+), защита била не по той цели.
//
// Девятый заход (owner 2026-08-13) — НАЙДЕНО И ИСПРАВЛЕНО. Диагностика на
// живом телефоне (временный debug-баннер, снят после разбора): при фокусе
// на «Заметка» (поле ниже по форме, требует авто-скролла) сам баннер
// (position:fixed; top:0) физически «уехал выше» видимой области экрана —
// возможно только если vv.offsetTop > 0. Разбор:
//   --kb-inset считается как innerHeight − vv.height − vv.offsetTop
//   (useVisualViewportInset.ts) — верно для элементов «в потоке» документа
//   (они физически панорамируются вместе со страницей, offsetTop
//   компенсирует то, что часть уже скрыта паном). Но для position:fixed
//   элемента это ДВОЙНОЙ учёт: сам пан уже сдвигает его физическое
//   положение независимо от CSS, а --kb-inset вычитает offsetTop ЕЩЁ РАЗ —
//   при offsetTop≈37px кнопка садилась на те же ~37px глубже в зону
//   клавиатуры/accessory-панели, чем нужно.
// Фикс: отдельная переменная --kb-height = innerHeight − vv.height, БЕЗ
// offsetTop — чистая высота клавиатуры, верная для fixed-элементов,
// которые сами не участвуют в панорамировании документа. --kb-inset не
// тронут (TaskDetailScreen и padding формы — «в потоке», там формула с
// offsetTop верна). max(..., safe-area-inset-bottom) убран — он никогда
// не срабатывал (413px инсета ≫ 34px safe-area), а теперь и не нужен:
// --kb-height корректен без запасного пути.
export function MicKeyboardBar({
  onStart,
  ariaLabel,
}: {
  onStart: () => void;
  ariaLabel: string;
}) {
  return createPortal(
    <div
      // Прижата к правому краю (right-[18px] — тот же отступ, что у FAB
      // в UI.tsx, канон плавающих круглых кнопок этого проекта), а не по
      // центру экрана: владелец 2026-08-13 попросил сдвинуть её
      // максимально вправо.
      //
      // z-[55], НЕ 45 (было до 20.08.2026): портал уходит в document.body,
      // а шторки вроде ReturnToWorkSheet/SubtaskFeed-формы — тоже прямые
      // дети body, но с z-50. При z-45 вся шторка (включая её textarea)
      // рисовалась ПОВЕРХ кнопки — геометрически кнопка на месте
      // (boundingBox есть), но physически невидима и некликабельна.
      // Владелец трижды жаловался «микрофон пропал в шторке ответа» —
      // причина была именно в этом, не в отсутствии самой кнопки.
      // Максимум z-index в проекте — 50 (шторки), поэтому 55 — выше
      // с запасом, а не подбор наугад.
      // Клик НЕ всплывает дальше. Портал живёт в document.body, но React
      // всплывает по дереву КОМПОНЕНТОВ: кнопка, отрисованная изнутри
      // шторки, отдавала клик её подложке (ReturnToWorkSheet — внешний div
      // с onClick={onCancel}), и шторка закрывалась в тот же миг, что
      // начиналась запись. Владелец 27.08.2026: «невозможно записать
      // голосом комментарий про возврат на доработку». Проверено
      // playwright'ом: после клика шторки нет, оверлея записи нет.
      onClick={(e) => e.stopPropagation()}
      className="fixed right-[18px] z-[55] pb-2"
      style={{
        // Низ видимой области, а не «высота клавиатуры». --kb-height —
        // разность с innerHeight, и она обнуляется, если layout-вьюпорт
        // ужимается вместе с видимой областью; тогда кнопка садится под
        // клавиатуру. max() оставляет прежнее поведение там, где разность
        // верна, и спасает там, где она врёт (20.08.2026, тот же разбор,
        // что у шторки возврата на доработку).
        bottom:
          "max(var(--kb-height, 0px), calc(100dvh - var(--vv-top, 0px) - var(--vv-height, 100dvh)))",
      }}
    >
      <button
        type="button"
        // Клик по кнопке не должен красть фокус у textarea (иначе blur
        // сорвал бы voiceTarget/keyboardFieldFocused раньше, чем onClick
        // успеет отработать) — preventDefault на mousedown держит фокус на
        // текстовом поле, стандартный приём для тулбар-кнопок.
        onMouseDown={(e) => e.preventDefault()}
        onClick={onStart}
        aria-label={ariaLabel}
        // Тот же «стеклянный» приём, что уже держат ScreenHeader/
        // SearchScreen (bg-bg/90 backdrop-blur-xl, components/UI.tsx) — не
        // свой рецепт, канон проекта, просто ниже opacity (было 70, не 90)
        // и сильнее blur: та панель на всю ширину экрана под контентом, эта
        // — маленький плавающий круг на фоне клавиатуры, ему нужна не
        // почти-непрозрачная подложка, а настоящее стекло.
        // Owner 2026-08-13 (девятый заход, три правки подряд, третья —
        // измерена численно, не на глаз): первая попытка (bg-bg/70
        // backdrop-blur-xl backdrop-saturate-150) добавила saturate, но
        // owner указал на разницу со своим референсом — accessory-панелью
        // iOS, где текст/цвет чётко проступают. Вторая (bg-bg/35 +
        // blur-lg) была шагом в верную сторону, но owner на реальном
        // телефоне сказал «абсолютно ничего не сделали» — его собственный
        // скриншот подтвердил: текст под кнопкой стал виден по ФОРМЕ, но
        // цвет «выцветал» в тёмно-бордовый, не оставался насыщенным, как
        // на референсе. Корень: bg-bg/N — это непрозрачная ЗАЛИВКА,
        // нарисованная ПОВЕРХ уже отфильтрованного backdrop — она тонирует
        // именно ту насыщенность, которую saturate должен был поднять,
        // так что снижать /70→/35 просто урезало занавес, не убирало
        // источник тусклости.
        // Проверено объективно (playwright: 4 варианта рядом на одном
        // цветном паттерне, средний RGB через PIL, сравнение с эталонным
        // цветом полосы 204,34,34): bg-bg/35+blur-lg+sat150 дал (94,23,23)
        // — дальше всего от эталона. bg-bg/15+blur-md+saturate-180 дал
        // (134,31,31) — заметно ближе, при этом круг остаётся различимым
        // на любом фоне (вариант вообще без заливки, только
        // backdrop-brightness, был ближе всего по цвету, но визуально
        // почти пропадал — плохой компромисс для UI-элемента, который
        // должен быть виден всегда).
        //
        // Четвёртая правка (owner 2026-08-13): владелец — «контуров слова
        // не увидеть через твою кнопку, а через Apple можно» — и отдельно
        // попросил эффект линзы/зеркалирования по краям при движении.
        // Разведка (web-scout) подтвердила по независимым источникам: тот
        // эффект — не blur, а геометрическое SVG-искажение пикселей
        // (feDisplacementMap как значение backdrop-filter), и оно СЕЙЧАС НЕ
        // РАБОТАЕТ в Safari/WebKit — открытый баг bugs.webkit.org #245510
        // (заведён 2022, всё ещё open, PR от июля 2026 не смёрджен, не
        // отгружен ни в STP 247, ни в 248); официальный пост WebKit про
        // Safari 26/WWDC25 не упоминает такого API для веб-контента вообще
        // (только для WKWebView в нативных приложениях). Технология
        // рендерится только в Chromium — на iPhone владельца физически не
        // заработает, это архитектурное ограничение платформы (тот же
        // принцип, что и с accessory-панелью выше), не мой недочёт.
        // Читаемость контуров — решаемая часть, и не через прозрачность
        // заливки (та часть уже была верной): корень — сам радиус blur.
        // backdrop-blur-md (12px по шкале Tailwind) размывает текст в
        // однородное пятно независимо от плотности заливки. Проверено
        // объективно (playwright, inline backdrop-filter в обход Tailwind
        // JIT, чтобы тестовые произвольные классы гарантированно
        // применялись): blur(12px) — текст нечитаем; blur(2px) — буквы
        // различимы по силуэту сквозь стекло, как на референсе. Совет
        // независимого источника (LogRocket, статья про Liquid Glass в
        // CSS/SVG) тот же: «тёмная/однородная подложка чаще улучшает
        // читаемость сильнее, чем рост blur» — то есть радиус, не
        // прозрачность, был неверной ручкой всё это время.
        className="tap-scale w-11 h-11 rounded-full bg-bg/15 backdrop-blur-[2px] backdrop-saturate-[1.8] border border-stroke shadow-mic-glass flex items-center justify-center"
      >
        <Icon name="mic" size={20} className="text-text" />
      </button>
    </div>,
    document.body,
  );
}
