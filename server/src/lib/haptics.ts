//
// Плагин свой — ios/App/App/TFHapticsPlugin.swift, CoreHaptics. Почему не
// хватило @capacitor/haptics, подробно расписано в шапке того файла:
// коротко — он создаёт UIImpactFeedbackGenerator заново на каждый вызов и
// не готовит его, отчего КАЖДЫЙ удар на частой шкале выходит слабее
// заказанного, а его потолок .heavy ниже, чем CoreHaptics с intensity 1.0.
// Владелец 20.08.2026, дважды подряд: «чуть помощнее… чтобы поощутимее».
//
// @capacitor/haptics оставлен запасным путём: если свой плагин почему-то
// не зарегистрировался, отклик обязан остаться, пусть и слабее.
//
// Остальные три правила модуля:
//
//  1) На ВЕБЕ вызывать нечего — Capacitor подменяет плагин web-реализацией
//     поверх navigator.vibrate, которого в WebKit нет вовсе. Гасим по
//     isNativePlatform(), а не try/catch на каждой клавише.
//  2) Промисы НИКОГДА не ждём и не даём им всплыть: виброотклик —
//     украшение, его отказ не имеет права уронить обработчик жеста или
//     оставить unhandled rejection в логе устройства (а лог сейчас
//     единственный канал диагностики на телефоне).
//  3) Ограничителя частоты ЗДЕСЬ НЕТ, и это решение (владелец 20.08.2026:
//     «каждый щелчок перемещения будет виброотклик, а не какой-то там от
//     миллисекунд зависеть»). Отклик привязан к СОБЫТИЮ — перешли деление,
//     — и порог по времени этой связи противоречит. Флуда не будет и без
//     него: каждый вызывающий бьёт только по СМЕНЕ цели, а события идут не
//     чаще кадра (onDragMove у dnd-kit, rAF у барабана).
import { Capacitor, registerPlugin } from "@capacitor/core";
import { Haptics, ImpactStyle } from "@capacitor/haptics";

interface TFHapticsPlugin {
  /** intensity и sharpness — 0..1. Sharpness это не громкость, а резкость
   *  фронта: у щелчка шкалы он высокий, у «положил карточку» ниже. */
  tick(opts: { intensity: number; sharpness: number }): Promise<void>;
  prepare(): Promise<void>;
}

const TFHaptics = registerPlugin<TFHapticsPlugin>("TFHaptics");

const NATIVE = Capacitor.isNativePlatform();
// Есть ли свой плагин в этой сборке. Проверяется один раз: на вебе и в
// старых сборках его нет, и незачем на каждый щелчок ходить в реестр.
const HAS_TF = NATIVE && Capacitor.isPluginAvailable("TFHaptics");

// Одна строка в системный лог устройства при старте: «свой плагин или
// запасной». Тихая деградация — правильное поведение (вибрация не смеет
// ронять жест), но она же прячет факт, что отклик идёт слабым путём, а
// проверить его на Маке нечем — вибрация меряется только пальцем. Строка
// стоит копейку и снимает этот вопрос с логов.
// Одна строка в системный лог при старте: каким движком пошёл отклик.
// Тихая деградация — правильное поведение (вибрация не смеет ронять
// жест), но она же прячет факт, что отклик идёт слабым путём, а проверить
// его с Мака нечем — вибрация меряется только пальцем. Строка стоит
// копейку и снимает вопрос. Ею же 20.08.2026 и поймали незарегистрированный
// плагин: имя в Capacitor.Plugins было (его кладёт туда registerPlugin на
// стороне JS), а нативной реализации не было — см. LocalAIPlugin.swift,
// capacitorDidLoad().
if (NATIVE) {
  console.log(
    `[haptics] движок: ${HAS_TF ? "TFHaptics (CoreHaptics)" : "@capacitor/haptics (запасной)"}`,
  );
}

function fire(intensity: number, sharpness: number, fallback: ImpactStyle): void {
  if (!NATIVE) return;
  if (HAS_TF) void TFHaptics.tick({ intensity, sharpness }).catch(() => {});
  else void Haptics.impact({ style: fallback }).catch(() => {});
}

/** Разбудить Taptic Engine заранее — на захвате карточки и на первом
 *  касании барабана. Без этого первая засечка приходит позже и слабее
 *  остальных: движок просыпается на первом же событии. */
export function hapticWarmup(): void {
  if (!NATIVE || !HAS_TF) return;
  void TFHaptics.prepare().catch(() => {});
}

/**
 * Взяли объект пальцем: карточка «оторвалась» от полотна. Самый тяжёлый
 * отклик в приложении — момент захвата должен быть ни с чем не спутан.
 * Sharpness ниже, чем у засечек: подъём — это толчок, а не щелчок.
 */
export function hapticGrab(): void {
  hapticWarmup();
  fire(1.0, 0.5, ImpactStyle.Heavy);
}

/**
 * Пересекли границу: деление шкалы времени, соседняя карточка, соседнее
 * место в списке. Полная интенсивность при высокой резкости — это и есть
 * «щелчок», который ищется пальцем на ходу.
 */
export function hapticCross(): void {
  fire(0.85, 1.0, ImpactStyle.Medium);
}

/**
 * Крупная засечка — ровный час на сетке дня и на барабане. Отличается от
 * hapticCross НАМЕРЕННО: если щёлкать все деления одинаково, палец
 * чувствует ровный треск и не может сказать, где он находится. Разный вес
 * каждой четвёртой засечки даёт шкале «рельеф» — час читается на ощупь,
 * как щелчок оборота у механического регулятора. Разница держится на
 * КОНТРАСТЕ, поэтому поднимать обе одинаково бессмысленно.
 */
export function hapticNotch(): void {
  fire(1.0, 1.0, ImpactStyle.Heavy);
}

/** Отпустили: объект лёг на место. Плотный и глухой — приземление. */
export function hapticDrop(): void {
  fire(1.0, 0.3, ImpactStyle.Heavy);
}

/**
 * ⚠️ Вызывающих нет с 20.08.2026: своя экранная клавиатура отключена
 * (components/AppKeyboard.tsx), а системной отклик даёт сама iOS. Функция
 * оставлена вместе с клавиатурой — вернётся панель, вернётся и вызов.
 *
 * Клавиша своей экранной клавиатуры. Единственное место, оставшееся
 * лёгким при общем подъёме шкалы: клавиша срабатывает по нескольку раз в
 * секунду подряд, и вес, уместный для засечки времени, при наборе текста
 * превращается в тряску. У системной клавиатуры iOS отклик на клавишах
 * включается в «Звук и тактильные сигналы»; WKWebView своей клавиатуре
 * его не даёт — за неё это делаем мы.
 */
export function hapticKey(): void {
  fire(0.6, 0.8, ImpactStyle.Light);
}

export function hapticTap(): void {
  fire(0.7, 0.9, ImpactStyle.Light);
}

export function hapticSuccess(): void {
  fire(0.9, 0.9, ImpactStyle.Medium);
}

export function hapticError(): void {
  fire(1.0, 0.5, ImpactStyle.Heavy);
}

